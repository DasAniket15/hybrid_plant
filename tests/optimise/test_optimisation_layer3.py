"""
tests/optimise/test_optimisation_layer3.py
───────────────────────────────────────────
Step 4 validation — first true optimisation (design §11 Layer 3).

Unfixes the sizing variables and solves the single-year MILP, then validates
the optimum three ways:

  Layer 3A  Solver sanity:    MILP terminates optimal; sizing within bounds.
  Layer 3B  Global optimum:   free savings_npv ≥ any fixed sizing evaluated
                              under the *same* Pyomo objective (rigorous —
                              uses the benchmark sizing as the fixed point).
  Layer 3C  Oracle agreement: the Pyomo optimum, re-evaluated through the
                              FinanceEngine oracle (PlantEngine RTC dispatch,
                              full 25-year re-simulation), reproduces the
                              Pyomo objective within tolerance, and Pyomo's
                              ToD-optimal dispatch is ≥ the RTC heuristic.
  Layer 3D  vs Optuna:        Pyomo savings_npv ≥ Optuna best (reference in
                              optuna_reference.json).  Documented finding:
                              the live Optuna run found ZERO feasible trials
                              under the current config, so this bound is
                              trivially satisfied — see the difference report.

Reference data
──────────────
``optuna_reference.json`` is generated by the existing SolverEngine
(1500 trials, seed 42, current config) — regenerate with the snippet in
``_OPTUNA_REGEN_HINT`` if the config changes.

C-rate divergence (documented)
──────────────────────────────
solver.yaml exposes bess_charge/discharge_c_rate as scope:current, so Optuna
optimises them; the Pyomo model fixes C-rate per D3 (reads ``max`` = 1.0).
The benchmark sizing (conftest) uses C-rate 1.0, matching Pyomo, so Layer 3B
is a clean comparison.
"""

